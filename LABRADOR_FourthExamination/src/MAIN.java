    private void RECOMActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_RECOMActionPerformed
        try {
        int user = Integer.parseInt(RECOM_TF.getText());
        List<Integer> recommended = recommendFriends(user);

        if (recommended.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No recommendations found for User " + user);
            return;
        }

        DISPLAY.append("Friend recommendations for User " + user + ": " + recommended + "\n");

        for (int rec : recommended) {
            int choice = JOptionPane.showConfirmDialog(
                    this,
                    "Do you want to add recommended friend " + rec + " for User " + user + "?",
                    "Add Friend?",
                    JOptionPane.YES_NO_OPTION
            );

            if (choice == JOptionPane.YES_OPTION) {
                 addFriendship(user, rec);
                 DISPLAY.append("Added new friendship automatically: (" + user + ", " + rec + ")\n");
                }
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Please enter a valid user ID.");
    }
    }//GEN-LAST:event_RECOMActionPerformed

