    private void addFriendship(int user1, int user2) {
        friendsMap.putIfAbsent(user1, new ArrayList<>());
        friendsMap.putIfAbsent(user2, new ArrayList<>());

        if (!friendsMap.get(user1).contains(user2)) {
            friendsMap.get(user1).add(user2);
            }
        if (!friendsMap.get(user2).contains(user1)) {
            friendsMap.get(user2).add(user1);
            }
        }
    
    private List<Integer> recommendFriends(int user) {
        List<Integer> recommended = new ArrayList<>();
        if (!friendsMap.containsKey(user)) return recommended;

        Set<Integer> userFriends = new HashSet<>(friendsMap.get(user));

            for (int friend : userFriends) {
                List<Integer> friendsOfFriend = friendsMap.get(friend);
                    if (friendsOfFriend != null) {
            for (int possible : friendsOfFriend) {
                    if (possible != user && !userFriends.contains(possible) && !recommended.contains(possible)) {
                    recommended.add(possible);
                    }
                }
            }
        }

        return recommended;
    }
    
