    private void ADDActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ADDActionPerformed
        try {
            String s1 = ADD_TF1.getText().trim();
            String s2 = ADD_TF2.getText().trim();
            
            if (s1.isEmpty() || s2.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Enter both User IDs before adding friendship!");
                return;
            }

            int user1 = Integer.parseInt(s1);
            int user2 = Integer.parseInt(s2);
            
            addFriendship(user1, user2);
            DISPLAY.append("Friendship added: (" + user1 + ", " + user2 + ")\n");
            
            ADD_TF1.setText("");
            ADD_TF2.setText("");
        } 
        catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric user IDs.");
        }
    }//GEN-LAST:event_ADDActionPerformed

